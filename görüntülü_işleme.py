import numpy as np
import cv2

def conv2d_numpy(image, kernel, padding=0):
    if padding > 0:
        image = np.pad(
            image,
            ((padding, padding), (padding, padding)),
            mode="constant"
        )

    kh, kw = kernel.shape
    h, w = image.shape

    output = np.zeros((h - kh + 1, w - kw + 1))

    for i in range(output.shape[0]):
        for j in range(output.shape[1]):
            region = image[i:i + kh, j:j + kw]
            output[i, j] = np.sum(region * kernel)

    return output


class SimpleCNN:
    """
    Saf NumPy CNN — Forward Pass
    Input 64x64
    Conv 3x3
    ReLU
    MaxPool 2x2
    Flatten
    Dense
    Softmax
    """

    def __init__(self, n_filters=4, input_size=64, n_classes=6, seed=42):
        rng = np.random.default_rng(seed)

        self.n_filters = n_filters
        self.input_size = input_size
        self.n_classes = n_classes

        self.conv_kernels = rng.standard_normal((n_filters, 3, 3)) * 0.1
        self.conv_biases = np.zeros(n_filters)

        pooled_h = input_size // 2
        pooled_w = input_size // 2
        flat_size = n_filters * pooled_h * pooled_w

        self.dense_W = rng.standard_normal((flat_size, n_classes)) * 0.1
        self.dense_b = np.zeros(n_classes)

        self.activations = {}

    def conv_layer(self, image):
        feature_maps = []

        for i, kernel in enumerate(self.conv_kernels):
            fm = conv2d_numpy(image, kernel, padding=1)
            fm = fm + self.conv_biases[i]
            feature_maps.append(fm)

        return np.stack(feature_maps, axis=0)

    def relu_layer(self, x):
        return np.maximum(0, x)

    def max_pool(self, feature_maps, pool_size=2, stride=2):
        n, h, w = feature_maps.shape

        h_out = h // stride
        w_out = w // stride

        pooled = np.zeros((n, h_out, w_out))

        for f in range(n):
            for i in range(h_out):
                for j in range(w_out):
                    r0 = i * stride
                    r1 = r0 + pool_size
                    c0 = j * stride
                    c1 = c0 + pool_size

                    pooled[f, i, j] = feature_maps[f, r0:r1, c0:c1].max()

        return pooled

    def dense_layer(self, flat_input):
        return flat_input @ self.dense_W + self.dense_b

    def softmax(self, logits):
        e = np.exp(logits - np.max(logits))
        return e / np.sum(e)

    def forward(self, image):
        self.activations["input"] = image

        conv_out = self.conv_layer(image)
        self.activations["conv"] = conv_out

        relu_out = self.relu_layer(conv_out)
        self.activations["relu"] = relu_out

        pool_out = self.max_pool(relu_out)
        self.activations["pool"] = pool_out

        flat_out = pool_out.flatten()
        self.activations["flat"] = flat_out

        dense_out = self.dense_layer(flat_out)
        self.activations["dense"] = dense_out

        probs = self.softmax(dense_out)
        self.activations["output"] = probs

        return probs


