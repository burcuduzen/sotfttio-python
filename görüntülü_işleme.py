def saliency_map_perturbation(model, image_flat, target_class, img_size=64, step=4):
    """
    Görüntü üzerinde küçük blokları sırayla kapatır.
    Hangi blok kapatılınca modelin güveni düşüyorsa, o bölge önemlidir.
    """

    base_prob = model.predict_proba([image_flat])[0][target_class]

    saliency = np.zeros((img_size, img_size))
    image_2d = image_flat.reshape(img_size, img_size)

    for r in range(0, img_size, step):
        for c in range(0, img_size, step):

            perturbed = image_2d.copy()
            perturbed[r:r + step, c:c + step] = 0

            perturbed_flat = perturbed.reshape(1, -1)

            perturbed_prob = model.predict_proba(perturbed_flat)[0][target_class]

            importance = base_prob - perturbed_prob

            saliency[r:r + step, c:c + step] = importance

    return saliency


